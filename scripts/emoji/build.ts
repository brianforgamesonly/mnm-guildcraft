// Order 24 (ITEM 3): the GuildCraft emoji the Worker uploads to each server, derived from assets/emoji/guildcraft.png (the
// owner's bot icon, downscaled to 128x128). The Worker cannot read a binary file, so the image is held as a base64 module:
//   node scripts/emoji/build.ts           writes src/emoji-image.ts from the PNG
//   node scripts/emoji/build.ts --check   fails when src/emoji-image.ts does not match the PNG (CI)
// Discord: "the 128x128 emoji image"; "Emojis and animated emojis have a maximum file size of 256 KiB" (Create Guild Emoji).
import { readFileSync, writeFileSync } from 'node:fs';

export const EMOJI_MAX_BYTES = 256 * 1024;
const png = new URL('../../assets/emoji/guildcraft.png', import.meta.url);
const out = new URL('../../src/emoji-image.ts', import.meta.url);

export function emojiModule(bytes: Buffer): string {
  if (bytes.length > EMOJI_MAX_BYTES) throw new Error(`the emoji is ${bytes.length} bytes, over Discord's 256 KiB`);
  if (bytes.readUInt32BE(16) !== 128 || bytes.readUInt32BE(20) !== 128) throw new Error('the emoji is not 128x128');
  return [
    '// Generated by scripts/emoji/build.ts from assets/emoji/guildcraft.png. Do not edit: run the script.',
    `/** The GuildCraft emoji as a data URI (Create Guild Emoji's image), ${bytes.length} bytes of PNG, 128x128. */`,
    `export const EMOJI_IMAGE = 'data:image/png;base64,${bytes.toString('base64')}';`,
    '',
  ].join('\n');
}

if (import.meta.main) {
  const want = emojiModule(readFileSync(png));
  if (process.argv.includes('--check')) {
    const have = readFileSync(out, 'utf8');
    if (have !== want) throw new Error('src/emoji-image.ts does not match assets/emoji/guildcraft.png: run node scripts/emoji/build.ts');
    console.log('src/emoji-image.ts matches assets/emoji/guildcraft.png');
  } else {
    writeFileSync(out, want);
    console.log(`wrote src/emoji-image.ts (${readFileSync(png).length} bytes of PNG)`);
  }
}
